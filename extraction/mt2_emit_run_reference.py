#!/usr/bin/env python3
"""Write docs/run_save_reference.md: GUID reference tables for run/save records.

Generated (do not hand-edit) from out/guid_names.json, out/class_champions.json
and RunHistory.json (to pair each Pyre Heart character with its artifact).
Re-run after a game patch:
  python3 extraction/mt2_guid_scan.py
  python3 extraction/mt2_resolve_guids.py
  python3 extraction/mt2_emit_run_reference.py [RunHistory.json]
"""
import json, os, re, sys, collections
sys.path.insert(0, os.path.dirname(__file__))
from mt2_decode_runs import CHAMPION_BY_CARD, TRIAL_NAMES, WAVE_SETS, BOSS_VARIANTS, LIFEMOTHER

hist = sys.argv[1] if len(sys.argv) > 1 else 'mt2-save-copy/run-history/RunHistory.json'
N = json.load(open('out/guid_names.json'))
CC = json.load(open('out/class_champions.json'))
by_internal = collections.defaultdict(list)
for g, v in N.items():
    by_internal[v['internal']].append(g)

CHAMP_DISPLAY = {  # ClanSelect key from ClassData -> display name
    'Awoken': 'The Sentient', 'Awoken_Exile': 'Wyldenten', 'Banished_Fel': 'Fel', 'Banished_Talos': 'Talos',
    'Hellhorned': 'Hornbreaker Prince', 'Hellhorned_Exile': 'Shardtail Queen',
    'LazLeague_Orechi': 'Orechi', 'LazLeague_Grael': 'Baron Grael',
    'LunaCoven_Ekka': 'Ekka', 'LunaCoven_Arduhn': 'Arduhn',
    'Pyreborne_Fenix': 'Lord Fenix', 'Pyreborne_Gilda': 'Lady Gilda',
    'Railforged_Herzal': 'Herzal', 'Railforged_Heph': 'Heph',
    'Remnant': 'Rector Flicker', 'Remnant_Exile': 'Little Fade',
    'Stygian': 'Tethys Titansbane', 'Stygian_Exile': 'Solgard the Martyr',
    'Umbra': 'Penumbra', 'Umbra_Exile': 'Primordium',
    'Underlegion_Bolete': 'Bolete the Guillotine', 'Underlegion_Lionsmane': 'Madame Lionsmane',
    'Wurmkin': 'Spine Chief', 'Wurmkin_Exile': 'Echowright',
}

L = []
w = L.append
w('# Run / save GUID reference tables\n')
w('*Generated by `extraction/mt2_emit_run_reference.py` from the game data; do not hand-edit.*\n')

# clans
w('## Clans and champions (`classId`, `championIndex`)\n')
w('| Clan | `classId` | `championIndex` 0 | `championIndex` 1 |')
w('|---|---|---|---|')
for cname, c in sorted(CC.items(), key=lambda kv: N[kv[1]['guid']]['name'] or ''):
    ch = [CHAMP_DISPLAY.get(x['clanSelect'], x['clanSelect']) for x in c['champions']]
    w('| %s | `%s` | %s | %s |' % (N[c['guid']]['name'], c['guid'], ch[0], ch[1]))

# hearts (pair char with artifact by observed co-occurrence)
pairs = collections.Counter()
for e in json.load(open(hist))['_runEntries']:
    d = json.loads(e['runDataJson'])
    pairs[(d['startingConditions']['pyreCharacterId'], d['pyreArtifactState']['relicDataID'])] += 1
w('\n## Pyre Hearts (`startingConditions.pyreCharacterId`, `pyreArtifactState.relicDataID`)\n')
w('| Heart | character GUID | artifact GUID |')
w('|---|---|---|')
for (cg, ag), n in sorted(pairs.items(), key=lambda kv: N[kv[0][0]]['name'] or ''):
    w('| %s | `%s` | `%s` |' % (N[cg]['name'], cg, ag))
w('\n(13 hearts; every pair was observed in the history. The picker also has a "Random" option that is not a heart.)\n')

# souls
w('## Souls (`souls[].relicDataID`, always the Tier III version)\n')
w('| Soul | T3 GUID (in run records) | T1 GUID | T2 GUID |')
w('|---|---|---|---|')
souls = {}
for g, v in N.items():
    m = re.match(r'(.+)T([123])$', v['internal'] or '')
    if v['kind'] == 'SoulData' and m:
        souls.setdefault(m.group(1), {})[m.group(2)] = g
for base, t in sorted(souls.items(), key=lambda kv: (N[kv[1]['3']]['name'] or '')):
    w('| %s | `%s` | `%s` | `%s` |' % ((N[t['3']]['name'] or base).replace(' III', ''), t['3'], t.get('1', ''), t.get('2', '')))

# trials
w('\n## Trials (`completedBattles[].trialID`; one GUID per ring tier)\n')
w('Tier by ring (fight order): Astrael and the 1st region = T1, 2nd region = T2, 3rd and 4th = T3.\n')
w('| Trial | T1 | T2 | T3 |')
w('|---|---|---|---|')
tr = collections.defaultdict(dict)
for g, v in N.items():
    m = re.match(r'T(\d)(.+?)\$?$', v['internal'] or '')
    if m and v['kind'] == 'unknown' and m.group(2) in TRIAL_NAMES and (v['internal'] or '').startswith('T'):
        tr[TRIAL_NAMES[m.group(2)]][m.group(1)] = g
for name, t in sorted(tr.items()):
    w('| %s | %s | %s | %s |' % (name, *['`%s`' % t[k] if k in t else '—' for k in '123']))

# region defeat mutators
w('\n## Region-defeat mutators (in `blessings[]`; which boss variant was beaten)\n')
w('| Region | Mutator no. | Mutator | Boss variant |')
w('|---|---|---|---|')
VARIANT_FOR_MUT = {  # mutator number -> scenarioIndex (solved from 52 runs)
    1: {1: 1, 2: 0, 3: 2}, 2: {1: 0, 2: 1, 3: 2}, 3: {1: 0, 2: 2, 3: 1}, 4: {1: 0, 2: 1, 3: 2}}
RN = {1: 'Maera', 2: 'Thaddeus', 3: 'Tivi', 4: 'Lylith'}
for rn in (1, 2, 3, 4):
    for k in (1, 2, 3):
        i = 'SoulSavior_Region%dComplete_%d' % (rn, k)
        g = by_internal[i][0]
        w('| %s | %d | %s (`%s`) | %s |' % (RN[rn], k, N[g]['name'], g, BOSS_VARIANTS[rn][VARIANT_FOR_MUT[rn][k]]))

# scenarios
w('\n## `scenarioIndex` meaning\n')
w('Index = position in the region\'s list in the game\'s `RunDataSoulSavior` object.\n')
w('| Battle slot (`battleIndex`) | index → name |')
w('|---|---|')
w('| 0 Astrael | 0 Infested (Mother\'s Hunter) · 1 Morsels (Mother\'s Flagellant) |')
for rn, (a, b) in {1: (1, 2), 2: (3, 4), 3: (5, 6), 4: (7, 8)}.items():
    ws = ' · '.join('%d %s' % kv for kv in WAVE_SETS[rn].items())
    bv = ' · '.join('%d %s' % kv for kv in BOSS_VARIANTS[rn].items())
    w('| %d %s wave set | %s |' % (a, RN[rn], ws))
    w('| %d %s boss | %s |' % (b, RN[rn], bv))
w('| 9 Lifemother | ' + ' · '.join('%d %s' % kv for kv in LIFEMOTHER.items()) + ' |')
open('docs/run_save_reference.md', 'w').write('\n'.join(L) + '\n')
print('wrote docs/run_save_reference.md,', len(L), 'lines')
